#!/usr/bin/env python3
"""Extract deterministic DXT blocks from a Source VTF into a C fixture."""

from __future__ import annotations

import argparse
import hashlib
import struct
import sys
from dataclasses import dataclass
from pathlib import Path

IMAGE_FORMATS = {
    13: ("BC1", 8, "DXT1"),
    14: ("BC2", 16, "DXT3"),
    15: ("BC3", 16, "DXT5"),
}


@dataclass(frozen=True)
class Vtf:
    width: int
    height: int
    depth: int
    mip_count: int
    image_format: int
    data_offset: int
    data: bytes


def parse_vtf(path: Path) -> Vtf:
    payload = path.read_bytes()
    if payload[:4] != b"VTF\0":
        raise ValueError("not a VTF file")
    major, minor, header_size = struct.unpack_from("<III", payload, 4)
    width, height = struct.unpack_from("<HH", payload, 16)
    if header_size < 64 or header_size > len(payload):
        raise ValueError("unsupported or truncated VTF header")
    image_format = struct.unpack_from("<I", payload, 52)[0]
    mip_count = payload[56]
    low_format = struct.unpack_from("<I", payload, 57)[0]
    low_width = payload[61]
    low_height = payload[62]
    depth = struct.unpack_from("<H", payload, 63)[0] if (major, minor) >= (7, 2) else 1
    low_size = 0
    if low_format != 0xFFFFFFFF:
        if low_format in (13, 14, 15):
            block_bytes = IMAGE_FORMATS[low_format][1]
            low_size = ((low_width + 3) // 4) * ((low_height + 3) // 4) * block_bytes
        elif low_format == 0:
            low_size = low_width * low_height * 4
        else:
            raise ValueError(f"unsupported low-resolution VTF format {low_format}")
    return Vtf(
        width=width,
        height=max(1, height),
        depth=max(1, depth),
        mip_count=max(1, mip_count),
        image_format=image_format,
        data_offset=header_size + low_size,
        data=payload,
    )


def mip_size(vtf: Vtf, mip: int) -> tuple[int, int, int]:
    width = max(1, vtf.width >> mip)
    height = max(1, vtf.height >> mip)
    depth = max(1, vtf.depth >> mip)
    block_bytes = IMAGE_FORMATS[vtf.image_format][1]
    return width, height, ((width + 3) // 4) * ((height + 3) // 4) * block_bytes * depth


def choose_mip(vtf: Vtf, requested: int | None) -> int:
    if requested is not None:
        if requested < 0 or requested >= vtf.mip_count:
            raise ValueError(f"mip {requested} is outside 0..{vtf.mip_count - 1}")
        return requested
    for mip in range(vtf.mip_count):
        width, height, _size = mip_size(vtf, mip)
        if width <= 512 and height <= 512 and width >= 64 and height >= 64:
            return mip
    return 0


def mip_offset(vtf: Vtf, mip: int) -> int:
    # Source stores mip data from smallest to largest.
    return vtf.data_offset + sum(mip_size(vtf, index)[2] for index in range(mip + 1, vtf.mip_count))


def make_fixture(path: Path, vtf: Vtf, mip: int) -> tuple[bytes, int, int, int]:
    width, height, size = mip_size(vtf, mip)
    if width % 4 or height % 4:
        raise ValueError("fixture requires block-aligned mip dimensions")
    offset = mip_offset(vtf, mip)
    data = vtf.data[offset : offset + size]
    if len(data) != size:
        raise ValueError("VTF mip data is truncated")
    block_bytes = IMAGE_FORMATS[vtf.image_format][1]
    row_blocks = width // 4
    height_blocks = height // 4
    positions = (
        (0, 0),
        (max(0, row_blocks // 2 - 1), max(0, height_blocks // 2 - 1)),
        (row_blocks - 1, height_blocks - 1),
    )
    blocks = b"".join(
        data[(y * row_blocks + x) * block_bytes : (y * row_blocks + x + 1) * block_bytes]
        for x, y in positions
    )
    return blocks, width, height, mip


def emit_c(
    path: Path,
    source: str,
    vtf: Vtf,
    mip: int,
    blocks: bytes,
    width: int,
    height: int,
) -> None:
    name, block_bytes, label = IMAGE_FORMATS[vtf.image_format]
    values = ", ".join(f"0x{byte:02x}" for byte in blocks)
    text = f"""/* Generated by vtf_fixture.py; do not edit. */
/* Source: {source} */
/* SHA-256: {hashlib.sha256(vtf.data).hexdigest()} */
#pragma once
#include <stddef.h>
#include <stdint.h>

#define BC_REAL_FORMAT {vtf.image_format}u
#define BC_REAL_FORMAT_NAME "{label}"
#define BC_REAL_BLOCK_BYTES {block_bytes}u
#define BC_REAL_WIDTH {width}u
#define BC_REAL_HEIGHT {height}u
#define BC_REAL_MIP {mip}u

static const uint8_t bc_real_sample_blocks[] = {{{values}}};
static const size_t bc_real_sample_block_count =
    sizeof(bc_real_sample_blocks) / BC_REAL_BLOCK_BYTES;
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("vtf", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--mip", type=int)
    parser.add_argument("--source-name", help="stable source identity stored in the fixture")
    args = parser.parse_args()
    vtf = parse_vtf(args.vtf)
    if vtf.image_format not in IMAGE_FORMATS:
        raise ValueError(f"VTF format {vtf.image_format} is not a supported DXT format")
    mip = choose_mip(vtf, args.mip)
    blocks, width, height, mip = make_fixture(args.vtf, vtf, mip)
    emit_c(
        args.output,
        args.source_name or args.vtf.name,
        vtf,
        mip,
        blocks,
        width,
        height,
    )
    print(
        f"{args.output}\t{IMAGE_FORMATS[vtf.image_format][2]} "
        f"{width}x{height} mip={mip} blocks={len(blocks) // IMAGE_FORMATS[vtf.image_format][1]}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
