#!/usr/bin/env python3
"""Generate the native geometry-stage feasibility fixture, not a runtime pass."""
from pathlib import Path
import struct
import subprocess
import tempfile

here = Path(__file__).resolve().parent
with tempfile.TemporaryDirectory(prefix='hybris-primitive-') as temporary:
    parts = []
    for name, source, options in (
        ('vertex', 'primitive.vert', ['-DNO_CULL=1']),
        ('cull_vertex', 'primitive.vert', []),
        ('cull_block_vertex', 'primitive.vert', ['-DCULL_BLOCK=1']),
        ('clip_cull_vertex', 'primitive.vert', ['-DCOMBINED_CLIP=1']),
        ('clip_cull_block_vertex', 'primitive.vert', ['-DCOMBINED_CLIP=1', '-DCULL_BLOCK=1']),
        ('cull', 'primitive.geom', []),
        ('lines', 'primitive.geom', ['-DPRIMITIVE_LINES=1']),
    ):
        binary = Path(temporary) / (name + '.spv')
        subprocess.run(['glslangValidator', '-V', *options, str(here/source), '-o', str(binary)], check=True)
        data = binary.read_bytes()
        words = list(struct.unpack('<' + 'I' * (len(data)//4), data))
        if name in ('cull_vertex', 'clip_cull_vertex'):
            at, changed = 5, 0
            while at < len(words):
                count, op = words[at] >> 16, words[at] & 65535
                if op == 71 and count == 4 and words[at+2:at+4] == [30, 1]:
                    words[at+2:at+4] = [11, 4]
                    changed += 1
                at += count
            assert changed == 1
            words[5:5] = [(2 << 16) | 17, 33]
            binary.write_bytes(struct.pack('<' + 'I' * len(words), *words))
        subprocess.run(['spirv-val', '--target-env', 'vulkan1.1', str(binary)], check=True)
        parts.append('static const uint32_t primitive_' + name + '_spv[] = {\n' +
                     ''.join('    ' + ', '.join(f'0x{word:08x}' for word in words[i:i+8]) + ',\n'
                             for i in range(0, len(words), 8)) + '};\n')
    (here/'primitive.inc').write_text('// Generated by generate-primitive.py.\n' + ''.join(parts))
