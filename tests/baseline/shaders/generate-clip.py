#!/usr/bin/env python3
"""Compile VS/FS fixtures for clip-distance emulation."""
from pathlib import Path
import struct
import subprocess
import tempfile
here = Path(__file__).resolve().parent
with tempfile.TemporaryDirectory(prefix='hybris-clip-') as tmp:
    output = []
    for name, source in [('Vertex', 'clip.vert'), ('Fragment', 'clip.frag'), ('CullVertex', 'clip.vert'), ('BlockCullVertex', 'clip.vert'), ('SpanVertex', 'clip.vert'), ('WideVertex', 'clip.vert'), ('MemberVertex', 'clip.vert')]:
        path = Path(tmp) / (name + '.spv')
        stage = 'vert' if source.endswith('.vert') else 'frag'
        options = ['-DACTIVE_CULL=1'] if name == 'CullVertex' else []
        if name == 'BlockCullVertex':
            options = ['-DACTIVE_CULL=2']
        for span, fixture in enumerate(('SpanVertex', 'WideVertex', 'MemberVertex'), 1):
            if name == fixture:
                options = [f'-DLOCATION_SPAN={span}']
        subprocess.run(['glslangValidator', '-V', '-S', stage, *options, str(here / source), '-o', str(path)], check=True)
        data = path.read_bytes()
        words = list(struct.unpack('<' + 'I' * (len(data) // 4), data))
        if name == 'CullVertex':
            # GLSL groups built-ins in gl_PerVertex. Exercise the legal separate
            # SPIR-V variable form too, with an active two-distance output.
            at = 5
            changed = 0
            while at < len(words):
                count, op = words[at] >> 16, words[at] & 65535
                if op == 71 and count == 4 and words[at+2:at+4] == [30, 1]:
                    words[at+2:at+4] = [11, 4]  # BuiltIn CullDistance
                    changed += 1
                at += count
            assert changed == 1
            words[5:5] = [(2 << 16) | 17, 33]  # Capability CullDistance
            path.write_bytes(struct.pack('<' + 'I' * len(words), *words))
        subprocess.run(['spirv-val', '--target-env', 'vulkan1.0', str(path)], check=True)
        rows = ['    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',' for i in range(0, len(words), 8)]
        output.append('static const uint32_t kClip' + name + '[] = {\n' + '\n'.join(rows) + '\n};\n')
    (here / 'clip.inc').write_text('// Generated by generate-clip.py.\n' + '\n'.join(output))
